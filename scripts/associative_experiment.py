"""Declared three-seed architecture screen; all learning/scoring stays in CUDA."""
import argparse
from pathlib import Path
import shutil
import subprocess

from experiment_checkpoint import checkpoint, distribution
from extend_curriculum import read_schedule
from native_experiment import NativeCommands, binding_scores, read, sha, verified_manifest, write
from prepare_lessons import quoted


def run(exe, out, prepared, smoke=False):
    exe, prepared = exe.resolve(), prepared.resolve()
    manifest = verified_manifest(prepared)
    out.mkdir(parents=True, exist_ok=False)
    seeds = [1337] if smoke else [1337, 2026, 31415]
    reading_end, common_end, final_end = (16, 32, 64) if smoke else (6000, 10000, 34000)
    arms = [('selective', 'selective', 512), ('wide-selective', 'selective', 588),
            ('associative', 'associative', 512)]
    capacity, speech, save, log = (16, 16, 32, 64) if smoke else (1024, 500, 5000, 6000)
    validation = Path('data/prepared/development-v2-final/13853.txt').resolve()
    schedule = out/'curriculum.sg'
    schedule.write_text('SGCURRICULUM3\n'+
        f'{reading_end} {quoted((prepared/"reading.dat").as_posix())} 1 all 1\n'+
        f'{common_end} {quoted((prepared/"through-prerequisites.dat").as_posix())} 0.25 new 64\n'+
        f'{final_end} {quoted((prepared/"through-binding.dat").as_posix())} 0.25 new 64\n')
    _, stages = read_schedule(schedule)
    sources = [dict(source=s['source'].as_posix(), sha256=sha(s['source']),
                    bytes=len(s['content']), documents=len(s['content'].split(b'\x1e')),
                    end_update=s['end_update']) for s in stages]
    boundaries = [s['documents'] for s in sources]
    protocol = dict(status='smoke_only' if smoke else 'declared_before_training',
        seeds=seeds, arms=[name for name, _, _ in arms],
        models={name:dict(cell=cell, hidden=hidden, channels=256, layers=4) for name, cell, hidden in arms},
        chunk=128, tf32=True, learning_rate=.0003, later_stage_multiplier=.25, answer_emphasis=64,
        reading_end=reading_end, prerequisite_end=common_end, online_endpoints=[final_end],
        replay_policy='stage', replay_slots=capacity, replay_every=4, speak_every=speech,
        generated_bytes_per_speech=96, graph_speech=True, save_every=save, log_every=log,
        source_records=sources, schedule_sha256=sha(schedule), prepared_manifest_sha256=sha(prepared/'manifest.json'),
        selected_spec_sha256=manifest['spec_sha256'],
        validation_reader_sha256=sha(validation),
        probe_sha256={name:sha(prepared/name) for name in
            ('train.sgprobe','development.sgprobe','test.sgprobe','expanded-train-monitor.sgprobe')},
        executable_sha256=sha(exe), source_commit=subprocess.check_output(['git','rev-parse','HEAD'],text=True).strip(),
        driver_sha256=sha(Path(__file__)), shared_io_sha256=sha(Path(__file__).with_name('native_experiment.py')),
        primary_endpoint='Original development complete-group binding accuracy at 34000 online observations.',
        secondary_endpoints='Exact four-byte greedy answers, original/expanded train monitors, earlier-reader '
                            'loss change from 10000 observations, live-loop cost and graph decoding.',
        comparison='All arms train from scratch on identical selected source bytes and observation/replay schedules. '
                   'The associative and H512 selective arms share initial common weights. H588 selective has '
                   '104 more parameters than associative, controlling approximately for parameter count. '
                   'Generated byte contents and recurrence differ. Seeds are paired, not shared trained ancestors.',
        timing='Separate first-10000 and subsequent-24000 live-loop segments, including replay, speech, logging '
               'and checkpoint writes; excludes process setup and assessment. No concurrent GPU study processes.',
        reserved_test_evaluated=False,
        limits='Three-seed early screen at 24000 binding observations, not a full exposure or hyperparameter '
               'search. The assay uses two candidate answers and four-byte box/bag generation, not general language.')
    write(out/'protocol.json', protocol)
    native = NativeCommands(exe, out)
    rows = []
    for seed_index, seed in enumerate(seeds):
        ordered = arms[seed_index % len(arms):]+arms[:seed_index % len(arms)]
        for name, cell, hidden in ordered:
            destination = out/f'{seed}-{name}'
            native('live','--curriculum',schedule,'--out',destination,'--updates',common_end,
                   '--cell',cell,'--channels',256,'--hidden',hidden,'--layers',4,'--seed',seed,
                   '--lr',.0003,'--chunk',128,'--replay','stage','--replay-capacity',capacity,
                   '--replay-every',4,'--graph','--fast','--speak-every',speech,'--tokens',96,
                   '--prompt','The bird ','--validation',validation,'--eval-batches',32,
                   '--log-every',log,'--save-every',save)
            common = read(destination/'session.json')
            common_path = destination/f'checkpoint-{common_end}.ckpt'
            shutil.copyfile(destination/'latest.ckpt',common_path)
            native('live','--curriculum',schedule,'--resume',common_path,'--out',destination,
                   '--updates',final_end,'--prompt','The bird ','--validation',validation,'--eval-batches',32,
                   '--log-every',log,'--save-every',save)
            session = read(destination/'session.json')
            assert session['online_updates'] == final_end and session['gradient_reductions'] == 'ordered_v1'
            snapshot = destination/f'checkpoint-{final_end}.ckpt'
            shutil.copyfile(destination/'latest.ckpt',snapshot)
            meta, _, _, identity = checkpoint(snapshot)
            slots = distribution(snapshot,boundaries)
            assert slots == [capacity//3+int(i<capacity%3) for i in range(3)]
            row = dict(seed=seed,arm=name,cell=cell,hidden=hidden,online_updates=final_end,parameters=meta[14],
                       checkpoint_sha256=identity,initial_checkpoint_sha256=sha(destination/'initial.ckpt'),
                       prerequisite_checkpoint_sha256=sha(common_path),common_session=common,
                       stored_windows_by_source_stage=slots,session=session)
            row.update(binding_scores(native,snapshot,prepared,destination,final_end))
            native('decode-bench','--checkpoint',snapshot,'--out',destination/'decode',
                   '--tokens',96 if smoke else 512,'--rounds',2 if smoke else 7)
            row['decode'] = read(destination/'decode/benchmark.json')
            assert sha(snapshot) == identity
            rows.append(row)
            write(out/'partial.json',rows)
            print(f'{seed} {name}: dev={row["development"]["joint_accuracy"]:.4f}, '
                  f'reader={session["final_validation_loss"]:.5f}, '
                  f'live={session["elapsed_seconds"]:.2f}s, '
                  f'graph={row["decode"]["graph_us_per_byte"]:.1f}us/byte',flush=True)
        paired = [row for row in rows if row['seed']==seed]
        for field in ('online_updates','global_updates','replay_updates','observed_pairs','replay_pairs',
                      'generated_bytes','learning_rate','replay_state_bytes','replay_items'):
            assert len({row['session'][field] for row in paired}) == 1,(seed,field)
        counts = {row['arm']:row['parameters'] for row in paired}
        assert counts['wide-selective']-counts['associative'] == 104
    assert sha(exe) == protocol['executable_sha256']
    assert sha(validation) == protocol['validation_reader_sha256']
    assert sha(schedule) == protocol['schedule_sha256']
    verified_manifest(prepared)
    write(out/'comparison.json',dict(protocol=protocol,native_commands=len(native.commands),runs=rows))


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--exe',type=Path,default=Path('build/synapticgenesis.exe'))
    p.add_argument('--out',type=Path,required=True)
    p.add_argument('--prepared',type=Path,default=Path('data/prepared/binding-diversity-v1'))
    p.add_argument('--smoke',action='store_true')
    a = p.parse_args()
    run(a.exe,a.out,a.prepared,a.smoke)
